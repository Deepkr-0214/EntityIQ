#!/usr/bin/env python3
"""Held-out experiment for a pairwise business-entity matching model.

This script is deliberately separate from the production pipeline. It samples
S1 entities from the labelled training data, builds the existing S2+S3 blocker,
uses deterministic Address Rescue top-200 candidates, and never injects GT
pairs that were not generated by blocking.
"""
import sys
import time
import random
import heapq
from collections import defaultdict
from pathlib import Path

import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.preprocessing import StandardScaler

if sys.platform == "win32":
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
from src.preprocessing.normalization import normalize_record
from src.pipeline.run_pipeline import CompactBlockingIndex, stream_records, load_ground_truth
from src.features.similarity_features import compute_pairwise_features, FEATURE_COLUMNS
from src.evaluation.metrics import macro_f05

SPLITS = ROOT / "splits"
SAMPLE_PER_COUNTRY = 600
CAP = 200
SEED = 42
INDEX_PROGRESS_EVERY = 500_000

BLOCK_FEATURES = [
    "block_first_token", "block_name_prefix", "block_shared_name_tokens",
    "block_shared_address_numbers", "block_shared_address_tokens",
    "block_consonant_skeleton", "block_shared_consonant_ngrams",
    "address_rescue_score", "address_rescue_rank", "candidate_is_s3",
    "name_token_jaccard", "address_token_jaccard", "consonant_ngram_jaccard",
]
FEATURES = FEATURE_COLUMNS + BLOCK_FEATURES


def stratified_sample_and_split(gt, country, n, seed):
    """Sample by singleton/single-match/multi-match and split by S1 ID."""
    buckets = {"singleton": [], "single": [], "multi": []}
    for sid, matches in gt.items():
        cat = "singleton" if not matches else ("single" if len(matches) == 1 else "multi")
        buckets[cat].append(sid)
    total = sum(map(len, buckets.values()))
    if total < n:
        raise ValueError(f"{country}: only {total} GT S1s available, requested {n}")
    exact = {k: n * len(v) / total for k, v in buckets.items()}
    quotas = {k: int(exact[k]) for k in buckets}
    for k in sorted(buckets, key=lambda x: exact[x] - quotas[x], reverse=True)[:n - sum(quotas.values())]:
        quotas[k] += 1
    rng = random.Random(seed)
    split = {"train": set(), "calibration": set(), "validation": set()}
    selected_category = {}
    for cat, values in buckets.items():
        chosen = rng.sample(values, quotas[cat])
        rng.shuffle(chosen)
        n_train = int(len(chosen) * 0.60)
        n_cal = int(len(chosen) * 0.20)
        split["train"].update(chosen[:n_train])
        split["calibration"].update(chosen[n_train:n_train + n_cal])
        split["validation"].update(chosen[n_train + n_cal:])
        selected_category.update({sid: cat for sid in chosen})
    return split, selected_category, quotas


def score_candidate_features(s1, idx):
    """Produce all seven blocker features and exactly their existing union."""
    f = defaultdict(lambda: [0] * 7)
    if s1.get("ft"):
        for p in idx.first_token.get(s1["ft"], ()):
            f[p][0] = 1
    if s1.get("npfx"):
        for p in idx.name_prefix.get(s1["npfx"], ()):
            f[p][1] = 1
    for token in s1.get("ntoks", ()):
        for p in idx.name_tokens.get(token, ()):
            f[p][2] += 1
    for number in set(s1.get("anums", ())):
        for p in idx.addr_nums.get(number, ()):
            f[p][3] += 1
    if len(s1.get("atoks", ())) >= 2:
        for token in s1["atoks"]:
            for p in idx.addr_tokens.get(token, ()):
                f[p][4] += 1
    cs3 = s1.get("cskel3", "")
    if cs3 and len(cs3) >= 3:
        for p in idx.cskel3.get(cs3, ()):
            f[p][5] = 1
    if len(s1.get("cngrams", ())) >= 2:
        for gram in s1["cngrams"]:
            for p in idx.cngrams.get(gram, ()):
                f[p][6] += 1
    pool = {p for p, x in f.items()
            if x[0] or x[1] or x[2] or x[3] or x[5] or x[4] >= 2 or x[6] >= 2}
    return f, pool


def address_rescue_score(f):
    # Established Address Rescue weights, applied only to present blocker-pool candidates.
    return 8*f[0] + 7*f[1] + 2*f[2] + 8*f[3] + 6*f[4] + 6*f[5] + f[6]


def build_selected_candidates(country, s1_records, gt, s2_path, s3_path):
    print(f"\n{country.upper()}: build full existing S2+S3 index", flush=True)
    idx = CompactBlockingIndex()
    candidate_ids = []
    candidate_pos = {}
    seen = set()
    t0 = time.perf_counter()
    for path in (s2_path, s3_path):
        for eid, name, addr, ctry in stream_records(path):
            if eid in seen:
                continue
            seen.add(eid)
            rec = normalize_record(eid, name, addr, ctry)
            pos = len(candidate_ids)
            candidate_ids.append(eid)
            candidate_pos[eid] = pos
            idx.add(pos, rec)
            if len(candidate_ids) % INDEX_PROGRESS_EVERY == 0:
                print(f"  indexed {len(candidate_ids):,} ({time.perf_counter()-t0:.1f}s)", flush=True)
    print(f"  index ready: {len(candidate_ids):,} ({time.perf_counter()-t0:.1f}s)", flush=True)

    selected = {}
    raw_hits_by_s1 = {}
    cap_hits_by_s1 = {}
    raw_truth_ids_by_s1 = {}
    true_in_raw = true_in_cap = true_total = 0
    for i, s1 in enumerate(s1_records.values(), 1):
        f, pool = score_candidate_features(s1, idx)
        truth = gt[s1["id"]]
        true_total += len(truth)
        raw_hits = sum(candidate_pos.get(mid) in pool for mid in truth)
        raw_hits_by_s1[s1["id"]] = raw_hits
        raw_truth_ids_by_s1[s1["id"]] = {mid for mid in truth if candidate_pos.get(mid) in pool}
        true_in_raw += raw_hits
        # Use stable candidate ID tie-break and retain only top 200.
        top = heapq.nsmallest(CAP, pool, key=lambda p: (-address_rescue_score(f[p]), candidate_ids[p]))
        top_set = set(top)
        cap_hits = sum(candidate_pos.get(mid) in top_set for mid in truth)
        cap_hits_by_s1[s1["id"]] = cap_hits
        true_in_cap += cap_hits
        selected[s1["id"]] = [(candidate_ids[p], tuple(f[p]), address_rescue_score(f[p]), rank)
                                for rank, p in enumerate(top, 1)]
        if i % 10 == 0 or i == len(s1_records):
            print(f"  generated capped pools {i}/{len(s1_records)}", flush=True)
    print(f"  Selected population blocking recall: uncapped={true_in_raw}/{true_total} "
          f"({true_in_raw/true_total if true_total else 1:.3%}); Address Rescue cap={true_in_cap}/{true_total} "
          f"({true_in_cap/true_total if true_total else 1:.3%})", flush=True)

    # Re-read source files and normalize only candidate records actually selected for this sample.
    needed = {cid for rows in selected.values() for cid, _, _, _ in rows}
    records = {}
    for path in (s2_path, s3_path):
        for eid, name, addr, ctry in stream_records(path):
            if eid in needed and eid not in records:
                records[eid] = normalize_record(eid, name, addr, ctry)
    missing = needed - records.keys()
    if missing:
        raise RuntimeError(f"{len(missing)} selected candidate IDs were not found in S2/S3 files")
    del idx, candidate_ids, candidate_pos, seen
    return selected, records, true_total, true_in_raw, true_in_cap, raw_hits_by_s1, cap_hits_by_s1, raw_truth_ids_by_s1


def make_feature_vector(s1, cand, blocker, rank):
    f = compute_pairwise_features(s1, cand)
    shared_name = blocker[2]
    shared_addr = blocker[4]
    shared_ngram = blocker[6]
    nt1, nt2 = s1.get("ntoks", set()), cand.get("ntoks", set())
    at1, at2 = s1.get("atoks", set()), cand.get("atoks", set())
    cg1, cg2 = s1.get("cngrams", set()), cand.get("cngrams", set())
    f.update({
        "block_first_token": blocker[0],
        "block_name_prefix": blocker[1],
        "block_shared_name_tokens": shared_name,
        "block_shared_address_numbers": blocker[3],
        "block_shared_address_tokens": shared_addr,
        "block_consonant_skeleton": blocker[5],
        "block_shared_consonant_ngrams": shared_ngram,
        "address_rescue_score": address_rescue_score(blocker),
        "address_rescue_rank": rank,
        "candidate_is_s3": int(cand["id"].startswith("S3-")),
        "name_token_jaccard": len(nt1 & nt2) / len(nt1 | nt2) if nt1 | nt2 else 0.0,
        "address_token_jaccard": len(at1 & at2) / len(at1 | at2) if at1 | at2 else 0.0,
        "consonant_ngram_jaccard": len(cg1 & cg2) / len(cg1 | cg2) if cg1 | cg2 else 0.0,
    })
    return [float(f.get(col, 0.0)) for col in FEATURES]


def featurize_split(split_name, s1_records, selected, candidate_records, gt):
    xs, ys, groups, cand_ids = [], [], {}, []
    for sid, s1 in s1_records.items():
        truth = gt[sid]
        rows = selected.get(sid, [])
        start = len(ys)
        for cid, blocker, score, rank in rows:
            cand = candidate_records[cid]
            xs.append(make_feature_vector(s1, cand, blocker, rank))
            ys.append(int(cid in truth))
            cand_ids.append(cid)
        groups[sid] = (start, len(ys))
    X = np.asarray(xs, dtype=np.float32)
    y = np.asarray(ys, dtype=np.int8)
    print(f"  {split_name}: {len(s1_records):,} S1, {len(y):,} candidate pairs, "
          f"positive={int(y.sum()):,}, negative={len(y)-int(y.sum()):,}", flush=True)
    return X, y, groups, cand_ids


def predict_sets(ids, groups, cand_ids, probs, threshold):
    out = {}
    for sid in ids:
        start, end = groups[sid]
        out[sid] = {cand_ids[i] for i in range(start, end) if probs[i] >= threshold}
    return out


def choose_threshold(cal_ids, cal_groups, cal_cands, cal_probs, gt):
    # Threshold uses calibration S1s only; final validation remains untouched.
    candidates = np.unique(np.quantile(cal_probs, np.linspace(0, 1, 401)))
    candidates = np.unique(np.concatenate(([0.0], candidates, [1.000001])))
    best = (-1.0, None, None)
    for threshold in candidates:
        preds = predict_sets(cal_ids, cal_groups, cal_cands, cal_probs, float(threshold))
        metrics = macro_f05(preds, {sid: gt[sid] for sid in cal_ids})
        key = (metrics["f05_macro"], metrics["precision_macro"], float(threshold))
        if key > best:
            best = key
    return best[2], best[0]


def summarize_errors(ids, groups, cids, probs, threshold, gt, selected):
    preds = predict_sets(ids, groups, cids, probs, threshold)
    false_pos, false_neg = [], []
    tp = fp = fn = 0
    for sid in ids:
        truth = gt[sid]
        pred = preds[sid]
        tp += len(truth & pred); fp += len(pred - truth); fn += len(truth - pred)
        false_pos.extend((sid, cid) for cid in sorted(pred - truth))
        false_neg.extend((sid, cid) for cid in sorted(truth - pred))
    metrics = macro_f05(preds, {sid: gt[sid] for sid in ids})
    return preds, metrics, (tp, fp, fn), false_pos, false_neg


def main():
    wall_start = time.perf_counter()
    all_s1 = {}; all_gt = {}; all_selected = {}; candidate_records = {}
    split_ids = {k: set() for k in ("train", "calibration", "validation")}
    categories = {}
    block_stats = {"total": 0, "raw_found": 0, "cap_found": 0}

    for country in ("india", "us"):
        gt_path = SPLITS / f"train_GT_{country}.tsv"
        s1_path = SPLITS / f"train_S1_{country}.tsv"
        s2_path = SPLITS / f"train_S2_{country}.tsv"
        s3_path = SPLITS / f"train_S3_{country}.tsv"
        gt = load_ground_truth(gt_path)
        split, cat_map, quotas = stratified_sample_and_split(gt, country, SAMPLE_PER_COUNTRY, SEED + (0 if country == "india" else 1))
        print(f"\n{country.upper()} sampled match categories={quotas}; "
              f"split sizes={ {k: len(v) for k,v in split.items()} }", flush=True)
        for name, ids in split.items(): split_ids[name].update(ids)
        categories.update(cat_map)

        wanted = set().union(*split.values())
        s1_records = {}
        for eid, name, addr, ctry in stream_records(s1_path):
            if eid in wanted:
                s1_records[eid] = normalize_record(eid, name, addr, ctry)
        if len(s1_records) != len(wanted):
            raise RuntimeError(f"{country}: loaded {len(s1_records)} of {len(wanted)} sampled S1 records")
        selected, cand_recs, ntrue, rawfound, capfound, raw_hits, cap_hits, raw_truth_ids = build_selected_candidates(
            country, s1_records, gt, s2_path, s3_path)
        all_s1.update(s1_records); all_gt.update({sid: gt[sid] for sid in wanted})
        all_selected.update(selected); candidate_records.update(cand_recs)
        block_stats["total"] += ntrue; block_stats["raw_found"] += rawfound; block_stats["cap_found"] += capfound
        block_stats.setdefault("raw_by_s1", {}).update(raw_hits)
        block_stats.setdefault("cap_by_s1", {}).update(cap_hits)
        block_stats.setdefault("raw_truth_ids_by_s1", {}).update(raw_truth_ids)

    # Build model matrices only after all disjoint S1 splits are fixed.
    matrices = {}
    for name in ("train", "calibration", "validation"):
        selected_records = {sid: all_s1[sid] for sid in sorted(split_ids[name])}
        matrices[name] = featurize_split(name, selected_records, all_selected, candidate_records, all_gt)
    Xtr, ytr, train_groups, train_cands = matrices["train"]
    Xca, yca, cal_groups, cal_cands = matrices["calibration"]
    Xva, yva, val_groups, val_cands = matrices["validation"]

    print("\nTraining class-weighted Logistic Regression", flush=True)
    fit_t = time.perf_counter()
    scaler = StandardScaler()
    Xtr_scaled = scaler.fit_transform(Xtr)
    model = LogisticRegression(max_iter=1000, class_weight="balanced", C=1.0,
                               solver="liblinear", random_state=SEED)
    model.fit(Xtr_scaled, ytr)
    print(f"  fit time={time.perf_counter()-fit_t:.2f}s; positives={int(ytr.sum())}, negatives={len(ytr)-int(ytr.sum())}", flush=True)

    pca = model.predict_proba(scaler.transform(Xca))[:, 1]
    threshold, cal_f05 = choose_threshold(sorted(split_ids["calibration"]), cal_groups, cal_cands, pca, all_gt)
    print(f"  calibration threshold={threshold:.6f}; calibration macro F0.5={cal_f05:.4f}", flush=True)
    pva = model.predict_proba(scaler.transform(Xva))[:, 1]
    val_ids = sorted(split_ids["validation"])
    preds, metrics, (tp, fp, fn), false_pos, false_neg = summarize_errors(
        val_ids, val_groups, val_cands, pva, threshold, all_gt, all_selected)

    val_true = sum(len(all_gt[sid]) for sid in val_ids)
    val_raw_tp = sum(block_stats["raw_by_s1"][sid] for sid in val_ids)
    val_cap_tp = sum(block_stats["cap_by_s1"][sid] for sid in val_ids)
    val_unblocked = val_true - val_raw_tp
    val_cap_drop = val_raw_tp - val_cap_tp
    val_model_fn = val_cap_tp - tp

    print("\nHELD-OUT VALIDATION (S1 entities held out; threshold chosen on separate calibration S1s)")
    print(f"  S1 entities evaluated: {len(val_ids)} (train={len(split_ids['train'])}, calibration={len(split_ids['calibration'])})")
    print(f"  Match counts: singleton={sum(not all_gt[s] for s in val_ids)}, "
          f"single={sum(len(all_gt[s])==1 for s in val_ids)}, multi={sum(len(all_gt[s])>1 for s in val_ids)}")
    print(f"  Macro precision={metrics['precision_macro']:.4f}; macro recall={metrics['recall_macro']:.4f}; macro F0.5={metrics['f05_macro']:.4f}")
    print(f"  Pair counts: TP={tp:,}; FP={fp:,}; FN={fn:,}")
    print(f"  Singleton correct={metrics['singleton_count'] - sum(bool(preds[s]) for s in val_ids if not all_gt[s])}/"
          f"{metrics['singleton_count']}; singleton F0.5={metrics['singleton_f05']:.4f}")
    print(f"  Validation true matches={val_true}; uncapped blocker found={val_raw_tp}; top-200 found={val_cap_tp}; "
          f"never generated={val_unblocked}; cap-dropped={val_cap_drop}; model-rejected={val_model_fn}")

    print("\nFALSE POSITIVE PAIRS (up to 20): S1_ID\tPREDICTED_CANDIDATE")
    for sid, cid in false_pos[:20]: print(f"  {sid}\t{cid}")
    print("FALSE NEGATIVE PAIRS (up to 20): S1_ID\tMISSED_TRUE_CANDIDATE\tSTATUS")
    for sid, cid in false_neg[:20]:
        selected_ids = {r[0] for r in all_selected[sid]}
        if cid in selected_ids:
            status = "generated and selected; model rejected"
        elif cid in block_stats["raw_truth_ids_by_s1"][sid]:
            status = "generated by blocker but dropped by top-200 cap"
        else:
            status = "not generated by blocker"
        print(f"  {sid}\t{cid}\t{status}")

    coefs = sorted(zip(FEATURES, model.coef_[0]), key=lambda x: abs(x[1]), reverse=True)
    print("\nLargest standardized logistic coefficients:")
    for name, value in coefs[:12]: print(f"  {name:34s} {value:+.4f}")
    print("\nEXPERIMENT SCOPE: training data only; no test inference; no submission files written.")
    print(f"Candidate files: splits/train_S1_{{india,us}}.tsv, train_S2_{{india,us}}.tsv, train_S3_{{india,us}}.tsv, train_GT_{{india,us}}.tsv")
    print(f"Total experiment wall time={time.perf_counter()-wall_start:.1f}s")


if __name__ == "__main__":
    main()
